create or replace view public.attendance_summary as
select student_id, subject, count(*)::integer as total_classes,
  count(*) filter (where status in ('present','late'))::integer as present_classes,
  round(100.0 * count(*) filter (where status in ('present','late')) / nullif(count(*), 0), 1) as percentage
from public.attendance
group by student_id, subject;

